import Link from "next/link";
import { requireViewer } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import { getOrCreateWeek, getTasks } from "@/lib/data";
import { addDays, dayLabel, mondayOf, todayISO, weekDays, weekLabel } from "@/lib/dates";
import { Shell } from "@/components/Shell";
import { TaskItem } from "@/components/TaskItem";
import { approveWeek, generateWeek, saveSummary, unapproveWeek, updateTask } from "@/app/actions";

export const dynamic = "force-dynamic";

export default async function WeekPage({ searchParams }: { searchParams: Promise<{ w?: string; error?: string; edit?: string }> }) {
  const viewer = await requireViewer();
  const sp = await searchParams;
  const monday = mondayOf(/^\d{4}-\d{2}-\d{2}$/.test(sp.w || "") ? sp.w! : todayISO());
  const supabase = await createClient();
  const week = await getOrCreateWeek(supabase, monday);
  const tasks = await getTasks(supabase, week.id);
  const days = weekDays(monday);
  const isOwner = viewer.role === "owner";
  const editing = tasks.find((t) => t.id === sp.edit);
  const memoCount = (await supabase.from("memos").select("id", { count: "exact", head: true }).eq("week_id", week.id)).count || 0;

  return (
    <Shell viewer={viewer} active="/week">
      <div className="mb-4 flex flex-wrap items-end justify-between gap-3">
        <div>
          <div className="eyebrow">Week plan</div>
          <h1 className="text-3xl font-semibold">{weekLabel(monday)}</h1>
          <p className="text-sm text-muted">
            <span className={week.status === "approved" ? "text-success" : "text-warning"}>
              {week.status === "approved" ? "Approved" : "Draft"}
            </span>
            {week.generated_at && ` · AI plan generated ${new Date(week.generated_at).toLocaleString("en-US", { timeZone: "America/Chicago", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })}`}
            {` · ${memoCount} memo${memoCount === 1 ? "" : "s"} this week`}
          </p>
        </div>
        <div className="flex gap-2">
          <Link className="btn btn-outline btn-sm" href={`/week?w=${addDays(monday, -7)}`}>← Last week</Link>
          <Link className="btn btn-outline btn-sm" href="/week">This week</Link>
          <Link className="btn btn-outline btn-sm" href={`/week?w=${addDays(monday, 7)}`}>Next week →</Link>
        </div>
      </div>

      {sp.error && <div className="card mb-4 border-danger/40 bg-red-50 p-3 text-sm text-danger">{sp.error}</div>}

      {isOwner && (
        <div className="card mb-6 grid gap-4 p-4 lg:grid-cols-2">
          <form action={generateWeek} className="space-y-2">
            <input type="hidden" name="week_start" value={monday} />
            <label className="label">Tell the AI what to change (optional), then generate</label>
            <textarea
              name="owner_notes"
              className="textarea"
              defaultValue={week.owner_notes}
              placeholder="e.g. Focus outbound on manufacturers this week. No lifestyle post Thursday, I'm travelling. Push the scorecard launch."
            />
            <div className="flex flex-wrap items-center gap-2">
              <button className="btn btn-primary">{week.generated_at ? "Regenerate the plan" : "Generate this week's plan"}</button>
              <span className="text-xs text-muted">Uses the memo, last week&apos;s numbers and the pipeline. Routine and hand-added tasks are kept.</span>
            </div>
          </form>
          <form action={saveSummary} className="space-y-2">
            <input type="hidden" name="week_start" value={monday} />
            <label className="label">This week in a few sentences (shown to both of you on Today)</label>
            <textarea name="summary" className="textarea" defaultValue={week.summary} placeholder="Generated by the AI; edit freely." />
            <div className="flex flex-wrap gap-2">
              <button className="btn btn-outline">Save summary</button>
              {week.status === "approved" ? (
                <button formAction={unapproveWeek} className="btn btn-outline">Reopen as draft</button>
              ) : (
                <button formAction={approveWeek} className="btn btn-dark">Approve the week</button>
              )}
            </div>
          </form>
        </div>
      )}

      {!isOwner && week.summary && (
        <div className="card mb-6 p-4 text-sm">
          <div className="eyebrow mb-1">This week</div>
          {week.summary}
        </div>
      )}

      {editing && isOwner && (
        <form action={updateTask} className="card mb-6 grid gap-3 p-4 sm:grid-cols-6">
          <input type="hidden" name="id" value={editing.id} />
          <div className="sm:col-span-6 text-sm font-semibold">Edit task</div>
          <div className="sm:col-span-4">
            <label className="label">Title</label>
            <input name="title" className="input" defaultValue={editing.title} />
          </div>
          <div className="sm:col-span-1">
            <label className="label">Day</label>
            <select name="day" className="select" defaultValue={editing.day}>
              {days.map((d) => (
                <option key={d} value={d}>{dayLabel(d)}</option>
              ))}
            </select>
          </div>
          <div className="sm:col-span-1">
            <label className="label">Who</label>
            <select name="assignee" className="select" defaultValue={editing.assignee}>
              <option value="owner">Xavier</option>
              <option value="va">VA</option>
            </select>
          </div>
          <div className="sm:col-span-5">
            <label className="label">Detail</label>
            <textarea name="detail" className="textarea" defaultValue={editing.detail} />
          </div>
          <div className="sm:col-span-1 flex flex-col justify-end gap-2">
            <button className="btn btn-primary justify-center">Save</button>
            <Link href={`/week?w=${monday}`} className="btn btn-outline justify-center">Cancel</Link>
          </div>
        </form>
      )}

      <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-7">
        {days.map((d) => {
          const dayTasks = tasks.filter((t) => t.day === d);
          const isToday = d === todayISO();
          return (
            <section key={d} className={`card p-3 ${isToday ? "ring-2 ring-gold" : ""}`}>
              <div className="mb-2 flex items-baseline justify-between">
                <h2 className="font-semibold">{dayLabel(d)}</h2>
                <Link href={`/?d=${d}`} className="text-xs text-gold-deep underline">open</Link>
              </div>
              {(["owner", "va"] as const).map((lane) => {
                const laneTasks = dayTasks.filter((t) => t.assignee === lane);
                if (laneTasks.length === 0) return null;
                return (
                  <div key={lane} className="mb-3">
                    <div className={`tag mb-1 ${lane === "owner" ? "tag-dark" : "tag-gold"}`}>{lane === "owner" ? "Xavier" : "VA"}</div>
                    <ul>
                      {laneTasks.map((t) => (
                        <li key={t.id} className={`py-1.5 text-sm ${t.status === "done" ? "text-muted line-through" : t.status === "skipped" ? "italic text-muted" : ""}`}>
                          <details>
                            <summary className="cursor-pointer">
                              {t.title}
                              {t.source === "ai" && <span className="ml-1 text-xs text-gold-deep">AI</span>}
                            </summary>
                            <div className="mt-1 border-l-2 border-line pl-2">
                              <TaskItem task={t} canEdit={isOwner} />
                              {isOwner && (
                                <Link href={`/week?w=${monday}&edit=${t.id}`} className="text-xs text-gold-deep underline">Edit</Link>
                              )}
                            </div>
                          </details>
                        </li>
                      ))}
                    </ul>
                  </div>
                );
              })}
              {dayTasks.length === 0 && <p className="text-xs text-muted">Nothing planned.</p>}
            </section>
          );
        })}
      </div>
    </Shell>
  );
}
